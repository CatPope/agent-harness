    pg.click('[data-arg=A-04]'); pg.fill('#npw', '12345678'); pg.fill('#npw2', '12345678'); pg.click('[data-act=savepw]'); pg.wait_for_timeout(200)
    ok('새 비밀번호 뒤 로그인 화면, 이메일 채움', pg.input_value('#lid') == 'minsu@example.com')
    pg.fill('#lpw', 'pw'); pg.click('[data-act=login]'); pg.wait_for_timeout(200)
    ok('로그인 후 홈', '다음 모임' in D().inner_text())
