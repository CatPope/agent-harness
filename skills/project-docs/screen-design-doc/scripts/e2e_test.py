    ok('템플릿 빈칸 인식', '새빈칸' in D().inner_text())
    pg.click('#devseg button[data-arg=pc]'); pg.click('.snav [data-arg=E-02]'); pg.click('[data-act=refresh]')
    ok('새로 고침 새 파일', '새 파일' in D().inner_text())
