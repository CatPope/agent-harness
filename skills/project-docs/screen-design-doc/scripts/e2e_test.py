    ok('할 일 카드로 C-03', '1/2' in D().inner_text())
    pg.click('[data-act=cycle][data-arg="1"]'); pg.click('[data-act=cycle][data-arg="3"]'); pg.click('[data-act=cycle][data-arg="3"]')
    ok('안 됨, 바뀔 수도 표시', pg.locator('.day.no').count() == 1 and pg.locator('.day.maybe').count() == 1)
    pg.click('[data-act=calview][data-arg=month]')
    ok('월간 보기 4주', pg.locator('.cal .day').count() == 28)
    pg.click('[data-act=step2]')
    ok('2단계 이동, 안 되는 날 제외', '2/2' in D().inner_text() and pg.locator('.trow').count() == 6)
    pg.click('[data-act=submitavail]'); pg.wait_for_timeout(2200)
