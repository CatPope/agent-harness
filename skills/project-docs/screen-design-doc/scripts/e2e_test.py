import sys, pathlib, glob
from playwright.sync_api import sync_playwright

sp = pathlib.Path.cwd() / 'out' / 'e2e'
sp.mkdir(parents=True, exist_ok=True)
# 사용: python e2e_test.py [데모 html]. 없으면 실행 폴더 out/ 의 가장 최근 데모를 연다.
f = sys.argv[1] if len(sys.argv) > 1 else sorted(glob.glob(str(pathlib.Path.cwd() / 'out' / '*화면 데모_v*.html')))[-1]
url = pathlib.Path(f).resolve().as_uri()
res = []


def ok(name, cond):
    res.append((name, bool(cond)))
    print('PASS' if cond else 'FAIL', name)


