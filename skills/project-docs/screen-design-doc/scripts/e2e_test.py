    n = pg.locator('.cand').count()
    ok(f'후보 {n}개 표시', n > 0)
    ok('2순위 후보 표시', '2순위' in D().inner_text())
    pg.locator('.cand').first.click(); pg.click('[data-act=castvote]'); pg.wait_for_timeout(1800)
    ok('투표 뒤 자동 확정', '자동 공지됨' in D().inner_text())
    ok('회원에게 변경 버튼 없음', pg.locator('[data-arg=change]').count() == 0)
    pg.select_option('#rolesel', '홍길동'); pg.wait_for_timeout(100)
