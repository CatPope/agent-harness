    pg.click('[data-act=dochange]'); pg.wait_for_timeout(200)
    ok('변경 뒤 재투표 화면', '다시 투표해요' in D().inner_text())
    ok('변경 알림 디스코드', '다시 투표해 주세요' in pg.inner_text('#dcfeed'))
